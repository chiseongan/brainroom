function keywordEmoji(word) {
  const w = (word || '').toLowerCase();
  if (w.length < 2) return '';
  for (const [words, emoji] of KEYWORD_EMOJI) {
    // 한 글자 단어(비·눈·약·팀 등)는 다른 단어 안에 우연히 들어가기 쉬워서 정확히 같을 때만
    if (words.some(k => (k.length === 1 ? w === k : w.includes(k) || k.includes(w)))) return emoji;
  }
  const theme = detectThemes(w)[0];
  return theme ? THEME_BY_ID[theme.id].emoji : '';
}
